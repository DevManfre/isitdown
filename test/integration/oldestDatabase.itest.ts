import { mock, test } from "node:test";
import assert from "node:assert/strict";
import { copyFile, mkdtemp, rm } from "node:fs/promises";
import type { AddressInfo } from "node:net";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { DatabaseSync } from "node:sqlite";
import { SCHEMA_VERSION } from "../../src/ui/db/migrate.ts";
import { buildUiRuntime } from "../../src/ui/runtime.ts";
import { createLogger } from "../../src/core/logger.ts";

/**
 * Roadmap 10.3: a database written by the oldest supported release, opened by
 * this build. Every other test starts from an empty file, so this is the one
 * that stands for the operator who has been running IsItDown since v1.0.0.
 *
 * The fixture is generated by `node tools/oldest-db.mjs` from that release's
 * own migrations (see the script for what is in it); its clock is the visual
 * harness's, 2026-09-01T12:00Z, so every window below is a fixed one.
 *
 * `Date` is frozen at that instant: the boot prunes history past retention by
 * the wall clock, and on the real one the fixture would lose a little more of
 * itself every day until this test proved nothing.
 */
mock.timers.enable({ apis: ["Date"], now: Date.parse("2026-09-01T12:00:00.000Z") });

const FIXTURE = new URL("../fixtures/db/oldest-supported.db", import.meta.url).pathname;

/** The fixture's ninety days of samples, the window the History view would ask for. */
const WINDOW = "from=2026-06-04&to=2026-09-01";

const userVersion = (path: string): number => {
  const db = new DatabaseSync(path, { readOnly: true });
  try {
    const [row] = db.prepare("PRAGMA user_version").all() as { user_version: number }[];
    return row?.user_version ?? 0;
  } finally {
    db.close();
  }
};

async function openFixture() {
  const dir = await mkdtemp(join(tmpdir(), "isitdown-oldest-"));
  const dbPath = join(dir, "isitdown.db");
  await copyFile(FIXTURE, dbPath);
  const before = userVersion(dbPath);

  const runtime = await buildUiRuntime({ dbPath, env: {}, logger: createLogger("error", () => {}) });
  const server = runtime.app.listen(0, "127.0.0.1");
  await new Promise<void>((resolve) => server.once("listening", () => resolve()));
  const base = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;

  return {
    before,
    runtime,
    get: async <T>(path: string): Promise<T> => {
      const response = await fetch(`${base}${path}`);
      assert.equal(response.status, 200, `${path} answered ${response.status}: ${await response.clone().text()}`);
      return (await response.json()) as T;
    },
    post: (path: string, body: unknown) =>
      fetch(`${base}${path}`, {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify(body),
      }),
    [Symbol.asyncDispose]: async () => {
      await new Promise<void>((resolve) => server.close(() => resolve()));
      await runtime.close();
      await rm(dir, { recursive: true, force: true });
    },
  };
}

test("the oldest supported database migrates and its data reads back through every main route", async () => {
  await using app = await openFixture();

  assert.equal(app.before, 7, "the fixture is v1.0.0's schema — regenerate it with tools/oldest-db.mjs");
  assert.equal(userVersion(app.runtime.dbPath), SCHEMA_VERSION);

  const status = await app.get<{
    providers: { id: string; overallStatus: string; activeIncidents: { id: string }[]; components: { id: string }[] }[];
  }>("/status");
  assert.deepEqual(status.providers.map((provider) => provider.id).sort(), ["anthropic", "cloudflare", "github", "vercel"]);
  const anthropic = status.providers.find((provider) => provider.id === "anthropic");
  assert.equal(anthropic?.overallStatus, "major_outage");
  assert.deepEqual(anthropic?.activeIncidents.map((incident) => incident.id), ["fixture-open-1"]);
  const cloudflare = status.providers.find((provider) => provider.id === "cloudflare");
  assert.deepEqual(cloudflare?.components.map((component) => component.id), ["cdn", "dns"]);

  const history = await app.get<{ aggregateUptime: number; dailyUptime: { day: string; uptime: number | null }[] }>(
    `/history?${WINDOW}`,
  );
  assert.equal(history.dailyUptime.length, 90);
  assert.ok(
    history.dailyUptime.every((day) => day.uptime !== null),
    "every day of the fixture's samples is still measured",
  );
  assert.ok(history.aggregateUptime < 100, "the outages in the samples still show");

  const incidents = await app.get<{ page: { items: { incidentId: string }[] } }>("/incidents");
  assert.deepEqual(
    incidents.page.items.map((incident) => incident.incidentId).sort(),
    ["fixture-open-1", "fixture-resolved-1", "fixture-resolved-2"],
  );

  const config = await app.get<{
    services: { id: string }[];
    polling: { intervalMinutes: number };
    channels: { id: string; enabled: boolean }[];
  }>("/config");
  assert.equal(config.services.length, 4);
  assert.equal(config.polling.intervalMinutes, 5);
  assert.equal(config.channels.find((channel) => channel.id === "telegram")?.enabled, true);

  const log = await app.get<{ notifications: { ok: boolean; error?: string }[] }>("/notifications");
  assert.equal(log.notifications.length, 4);
  assert.equal(log.notifications.filter((entry) => !entry.ok)[0]?.error, "HTTP 502");
});

test("tables the oldest release never had work on top of its data", async () => {
  await using app = await openFixture();
  const window = await app.get<{ dailyUptime: { day: string; uptime: number | null }[] }>(`/history?${WINDOW}`);

  // Retention folds the old samples into `daily_rollups` (schema 41) and
  // deletes them: the bars must come back the same out of the rollup.
  await app.runtime.store.pruneOlderThan(30);
  const rolled = app.runtime.db.prepare("SELECT COUNT(DISTINCT day) AS n FROM daily_rollups").get() as { n: number };
  assert.equal(rolled.n, 60, "the sixty days past a 30-day retention are rollups now");
  assert.deepEqual((await app.get<typeof window>(`/history?${WINDOW}`)).dailyUptime, window.dailyUptime);

  // Annotations (schema 24) hang off nothing the old release wrote, but are
  // read in the same window as its samples.
  const created = await app.post("/annotations", { at: "2026-08-15T10:00:00.000Z", label: "deploy", colour: "neutral" });
  assert.equal(created.status, 201);
  const { annotations } = await app.get<{ annotations: { label: string }[] }>(`/annotations?${WINDOW}`);
  assert.deepEqual(annotations.map((annotation) => annotation.label), ["deploy"]);
});
